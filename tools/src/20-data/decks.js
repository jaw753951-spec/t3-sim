/* 들인 팩과 바꿔 놓은 자리에서 가방 한 벌을 짓는다.
     on    {팩id:참} — fixed 팩은 여기 없어도 든다
     swap  {기본카드:놓아 둔 카드} — 안 적힌 자리는 기본 그대로 */
function packDeck(on, swap){
  const out = [];
  for(const p of PACKS){
    if(!p.fixed && !on[p.id]) continue;
    for(const base of p.cards) out.push(swap[base] || base);
  }
  return out;
}

/* 팩 하나를 누른 결과 편성. 자리 규칙은 여기 한 곳에만 있다.

   고른 팩은 늘 PACK_PICK 개다. 이미 그만큼 들었는데 새것을 누르면 **가장 먼저
   든 것**이 빠진다 (태그가 상한에서 밀리는 것과 같은 손 — 생성기.체력태그).
   든 팩을 다시 눌러도 안 빠진다: 빠지면 그 자리가 비는데, 빈 자리는 없다.

   차례는 on 의 열쇠 차례다 — 자바스크립트 객체는 글자 열쇠를 넣은 차례로 들고
   있다. 뺐다 다시 넣으면 맨 뒤로 간다. 그것이 여기서 바라는 바다 (다시 고른
   것이 가장 나중에 든 것이 된다). */
function packPick(on, id){
  const p = PACKS.find(x=>x.id===id); if(!p || p.fixed) return {...on};
  if(on[id]) return {...on};                      // 든 것을 다시 눌렀다 — 자리는 빌 수 없다
  const next = {...on, [id]:1};
  const picked = Object.keys(next);
  while(picked.length > PACK_PICK) delete next[picked.shift()];
  return next;
}

/* 이 팩을 넣으면 무엇이 밀려나는가 — 화면이 「무엇과 바뀌었다」를 말할 때 쓴다.
   미는 규칙을 화면이 따로 흉내 내면 곧 갈린다 */
function packOut(on, id){
  const before = Object.keys(on);
  const after  = Object.keys(packPick(on, id));
  return before.filter(x => !after.includes(x));
}

