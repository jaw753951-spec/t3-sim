const swapPool = id => SWAP.find(p => p.includes(id)) || [];

/* 들인 팩과 바꿔 놓은 자리에서 가방 한 벌을 짓는다.
     on    {팩id:참} — fixed 팩은 여기 없어도 든다
     swap  {기본카드:놓아 둔 카드} — 안 적힌 자리는 기본 그대로 */
function packDeck(on, swap){
  const out = [];
  for(const p of PACKS){
    if(!p.fixed && !(on||{})[p.id]) continue;
    for(const base of p.cards) out.push((swap||{})[base] || base);
  }
  return out;
}

