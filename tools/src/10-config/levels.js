/* ── 태그는 **두 겹**이다 ────────────────────────────────────
     체격       몸의 출발점. 하나만 고른다. 곱하지 않는다.
     체력 태그  그 위에 곱한다. 둘까지 붙는다.

   ★ 전에는 한 줄에 다 늘어놓고 TAG_CAP 을 통째로 걸었다. 둘이 틀렸다:
     ㄱ) 소아와 노동자가 서로를 안 밀어내 「소아 노동자」가 성립했다 —
        체격이 둘인 환자다. bodyHp 가 가장 얇은 쪽을 보게 막아 두긴 했지만,
        그것은 값이 안 흔들리게 한 것이지 고를 수 있는 것이 옳다는 뜻이 아니다.
     ㄴ) 체격을 고른 뒤 체력 태그를 둘 붙이면 상한에 밀려 **체격이 앞에서
        빠졌다** — 소아(120)로 지은 환자가 아무 말 없이 성인(170)이 됐다.
   상한은 곱하는 쪽에만 건다. 고르는 자를 나누는 것이 옳다.
   담기는 곳은 여전히 태그 배열 하나다 — 보스 표(20-data)와 hpOfTags 가
   그대로 돌아야 하므로 자료를 쪼개지 않고 **고르는 규칙만** 쪼갠다. */
//@ 생성기.체력태그 — 체격은 하나, 곱하는 태그는 둘까지
const TAG_CAP = 2;

/* 함께 붙지 않는 것들. 신분 묶음은 이제 체격이 하나뿐이라 구조가 막지만,
   보스 표는 손으로 적으므로 자는 남겨 둔다 — 여기가 곧 「같이 못 선다」의 집이다.
   나이 묶음(노인 ↔ 소아)은 **겹을 가로지른다**: 노인은 곱하는 태그이고 소아는
   체격이라, 겹을 나눈 뒤에도 이 표가 없으면 「소아 노인」이 성립한다 */
const TAG_GROUP = [['노인','소아'], ['노동자','군인','상층']];

/* 두 겹의 목록. 사람이 읽는 이름표는 여기 것이 아니다 — tagLabel(60-text)이 낸다.
   이 층의 계약은 숫자만 두는 것이다.
   체격은 성인도 낸다 — 하나를 고르는 칸이므로 기본값도 눌러야 하는 자리다.
   (담을 때는 안 담는다. 기본값을 태그 줄에 적어 두면 판 위 칩과 보스 표가
    서로 다른 꼴을 갖게 된다 — bodySet 을 볼 것) */
const BODY_LIST   = () => Object.keys(BODY_HP);
const HP_TAG_LIST = () => Object.keys(HP_TAG);

/* ── 체격 (v26) ─────────────────────────────────────────────
   환자 체력의 출발점. 레벨표가 아니라 몸이 정한다.
   체격 태그는 곱하는 값이 아니라 '어느 체격을 볼지 고르는' 값이다.
   태그에 체격 항목이 없으면 성인으로 본다 — 노인·상층이 그 경우다.
   ★ 노인은 두 곳에 다 든다: 체격은 성인(170)을 보고, 아래 체력 태그 ×0.85 를 받는다.
     소아 체격(120)으로 보내면 원래보다 지나치게 얇아진다. */
//@ 생성기.체격 — 환자 체력의 출발점. 태그가 어느 체격을 볼지 고른다
/* 상층도 제 줄을 갖는다. 값은 성인과 같지만, 줄이 없으면 아래 두 집합이
   이름을 손으로 끼워 넣어야 하고 — 실제로 그랬다 — 다음에 곱이 없는 태그를
   더할 때 hpOfTags 가 「모르는 체력 태그」로 판 짓는 중에 선다 */
const BODY_HP = { '소아':120, '성인':170, '상층':170, '노동자':200, '군인':200 };
const BODY_DEF = '성인';
/* 이 태그 줄이 말하는 체격 하나. 화면은 이제 하나만 고르게 하지만, 보스 표는
   손으로 적으므로 둘이 들어올 수 있다 — 그때 '먼저 적힌 것'을 보면 같은 태그
   한 벌인데 적은 차례에 따라 체력이 120 이 됐다 200 이 됐다 한다.
   가장 얇은 체격을 본다 — 차례를 안 타고, 소아 노동자는 노동을 해도 아이 몸이다. */
const bodyOf = tags => {
  const hit = (tags||[]).filter(t => BODY_HP[t]!==undefined);
  return hit.length ? hit.reduce((a,b)=> BODY_HP[b] < BODY_HP[a] ? b : a) : BODY_DEF;
};
const bodyHp = tags => BODY_HP[bodyOf(tags)];

/* ── 체력 태그 — 체격을 고른 뒤에 곱한다. 전부 ×0.85 하나로 통일했다.
   한 환자에 둘까지 붙으므로 가장 얇아져도 0.7225 다.
   체격이 태그에서 빠졌으니 예전의 세 겹 누적(0.578)은 나올 수 없다. */
const HP_TAG = {
  '영양실조':0.85, '굶주림':0.85, '만성기저질환':0.85,
  '재진악화':0.85, '공황시작':0.85, 'T3이식다수':0.85, '노인':0.85,
};

/* 아는 태그 — 체격을 고르는 것과 체력을 곱하는 것을 합친 것. 두 표가 곧 목록이다 */
const TAG_KNOWN = new Set([...Object.keys(BODY_HP), ...Object.keys(HP_TAG)]);

/* 모르는 태그를 떨군다.
   ★ hpOfTags 는 모르는 이름에 예외를 던진다 — 보스 표의 오타를 판 짓는 중에
     잡으려고 일부러 그렇게 뒀다. 그런데 그 예외가 **그리는 길** 위에 서면
     화면이 통째로 안 뜬다: 태그 칸이 hpOfTags 를 부르게 되면서, 오타가 든
     JSON 을 읽어들이면 만들기 탭이 그 뒤로 영영 안 그려졌다.
   그러니 예외는 그대로 두고, **밖에서 들어오는 자료**만 들어올 때 한 번 훑는다
   (JSON 읽어들이기 · 브라우저에 저장한 병 노드). 악보에 scoreClean 을 두는 것과
   같은 잣대다 — 안쪽은 여전히 시끄럽게 터진다. */
const tagsClean = tags => (tags||[]).filter(t => TAG_KNOWN.has(t));

/* 태그 목록에서 최종 체력을 낸다 — 생성기와 보스 표가 같은 자를 쓴다 */
const hpOfTags = tags => {
  let hp = bodyHp(tags);
  for(const t of (tags||[])){
    if(!TAG_KNOWN.has(t)) throw new Error('모르는 체력 태그: '+t);
    hp = Math.round(hp * (HP_TAG[t]||1));
  }
  return hp;
};

